import type { TypedDocumentString } from "@inmanta/web-console-core/GraphQL/generated/graphql";
import { createCustomError } from "./useFetchHelpers";
import { usePostWithoutEnv } from "./useQueries";

// TODO: https://github.com/inmanta/inmanta-core/issues/11187 drop the extra `data` wrapper once core returns a standard response.
/**
 * The body the orchestrator answers a GraphQL request with. It wraps the standard GraphQL response in an extra `data` field,
 * and its errors are plain messages.
 */
export interface GraphQLResponseBody<Result> {
  data: {
    data: Result;
    errors: string[] | null;
    extensions: Record<string, unknown>;
  };
}

/**
 * Hook that returns `execute`, which posts a GraphQL query to /api/v2/graphql and resolves to its result.
 * The query is a document generated by codegen, so the variables and the result are typed from the orchestrator's schema.
 * It rejects like a failed REST request, and also when the body holds GraphQL errors, with all of them joined as the message.
 *
 * @example
 * const GET_ENVIRONMENT_NAMES_QUERY = graphql(`
 *   query GetEnvironmentNames {
 *     environments { edges { node { name } } }
 *   }
 * `);
 *
 * const execute = useGraphQLRequest();
 * const { data } = useQuery({ queryKey: ["key"], queryFn: () => execute(GET_ENVIRONMENT_NAMES_QUERY) });
 * // data.environments.edges[0].node.name is typed as a string
 */
export const useGraphQLRequest = () => {
  const post = usePostWithoutEnv({ expectResponseBody: true });

  return async <Result, Variables>(
    query: TypedDocumentString<Result, Variables>,
    ...[variables]: Variables extends Record<string, never> ? [] : [NoInfer<Variables>]
  ): Promise<Result> => {
    const body = await post<unknown, GraphQLResponseBody<Result>>("/api/v2/graphql", {
      query,
      variables,
    });

    if (body.data.errors?.length) {
      throw createCustomError(body.data.errors.join(", "), 200);
    }

    return body.data.data;
  };
};
